    private final String url;
    private final String username;
    private final String password;

    public Database() {
        url = System.getenv().getOrDefault("DB_URL", "jdbc:postgresql://localhost:5432/fitness_tracker");
        username = System.getenv().getOrDefault("DB_USERNAME", "fitness");
        password = System.getenv().getOrDefault("DB_PASSWORD", "fitness_dev_only");
    }

    public Connection connect() throws SQLException {
        return DriverManager.getConnection(url, username, password);
    }

    public void initialize() throws SQLException {
        try (Connection connection = connect(); Statement statement = connection.createStatement()) {
            statement.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS users (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      email VARCHAR(254) NOT NULL UNIQUE,
                      display_name VARCHAR(80) NOT NULL,
                      password_hash VARCHAR(255) NOT NULL,
                      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
                    )
                    """);
            statement.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS exercises (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      name VARCHAR(100) NOT NULL,
                      muscle_group VARCHAR(30) NOT NULL,
                      equipment VARCHAR(20) NOT NULL,
                      owner_id BIGINT REFERENCES users(id)
                    )
                    """);
            statement.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS workouts (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      user_id BIGINT NOT NULL REFERENCES users(id),
                      started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                      finished_at TIMESTAMPTZ
                    )
                    """);
            statement.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS workout_sets (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      workout_id BIGINT NOT NULL REFERENCES workouts(id),
                      exercise_id BIGINT NOT NULL REFERENCES exercises(id),
                      reps INTEGER NOT NULL CHECK (reps > 0),
                      weight_kg DOUBLE PRECISION NOT NULL CHECK (weight_kg >= 0),
                      logged_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
                    )
                    """);
            statement.executeUpdate("CREATE UNIQUE INDEX IF NOT EXISTS exercises_builtin_name_unique ON exercises (lower(name)) WHERE owner_id IS NULL");
            statement.executeUpdate("CREATE UNIQUE INDEX IF NOT EXISTS exercises_custom_owner_name_unique ON exercises (owner_id, lower(name)) WHERE owner_id IS NOT NULL");
            statement.executeUpdate("CREATE INDEX IF NOT EXISTS workouts_user_started_idx ON workouts(user_id, started_at DESC)");
            statement.executeUpdate("CREATE INDEX IF NOT EXISTS workout_sets_workout_logged_idx ON workout_sets(workout_id, logged_at)");
            seedCatalog(connection);
        }
    }

    private void seedCatalog(Connection connection) throws SQLException {
        String sql = """
                INSERT INTO exercises(name, muscle_group, equipment, owner_id)
                SELECT ?, ?, ?, NULL
                WHERE NOT EXISTS (SELECT 1 FROM exercises WHERE owner_id IS NULL AND lower(name) = lower(?))
                """;
        try (var statement = connection.prepareStatement(sql)) {
            for (var exercise : CATALOG) {
                statement.setString(1, exercise.name());
                statement.setString(2, exercise.muscle());
                statement.setString(3, exercise.equipment());
                statement.setString(4, exercise.name());
                statement.executeUpdate();
            }
        }
    }
